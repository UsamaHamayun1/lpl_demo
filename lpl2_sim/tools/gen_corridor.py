#!/usr/bin/env python3
"""Generate the LPL 2.0 corridor artefacts from config/corridor.yaml.

    python3 tools/gen_corridor.py [--check]

Writes (into this package's source tree, committed to git):
  worlds/lpl2_corridor.sdf        Gazebo Harmonic world
  maps/corridor.{pgm,yaml}        Nav2 static map (static boxes only)
  maps/mask_p3_available.*        KeepoutFilter mask: Lane 1 forbidden except the passing window
  maps/mask_p3_unavailable.*      KeepoutFilter mask: Lane 1 forbidden everywhere
  maps/mask_none.*                KeepoutFilter mask: nothing forbidden (no lane discipline)
--check exits non-zero if any generated file is out of date (used by the tests).
"""
import argparse
import math
import os
import sys

import numpy as np

PKG = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, PKG)
from lpl2_sim.geometry import Corridor  # noqa: E402


def fmt(*v):
    return ' '.join(f'{x:.4g}' for x in v)


def material(rgba):
    c = fmt(*rgba)
    return f'<material><ambient>{c}</ambient><diffuse>{c}</diffuse></material>'


def box_model(name, size, pose, rgba, collision=True):
    geo = f'<geometry><box><size>{fmt(*size)}</size></box></geometry>'
    col = f'<collision name="collision">{geo}</collision>' if collision else ''
    return (f'    <model name="{name}">\n'
            f'      <static>true</static>\n'
            f'      <pose>{fmt(*pose)} 0 0 0</pose>\n'
            f'      <link name="link">{col}<visual name="visual">{geo}{material(rgba)}</visual></link>\n'
            f'    </model>\n')


def world_sdf(c):
    out = [f'''<?xml version="1.0" ?>
<!-- GENERATED by tools/gen_corridor.py from config/corridor.yaml. Do not edit by hand. -->
<sdf version="1.8">
  <world name="{c.world_name}">
    <physics type="ode">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>

    <scene>
      <ambient>0.6 0.6 0.6 1</ambient>
      <background>0.7 0.8 0.9 1</background>
      <shadows>false</shadows>
    </scene>
    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.8 0.8 0.8 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.3 0.2 -0.9</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision"><geometry><plane><normal>0 0 1</normal><size>80 30</size></plane></geometry></collision>
        <visual name="visual"><geometry><plane><normal>0 0 1</normal><size>80 30</size></plane></geometry>{material(c.colors['floor'])}</visual>
      </link>
    </model>

    <!-- Static structure (also in the Nav2 map) -->
''']
    for b in c.static_boxes:
        out.append(box_model(b.name, b.size, b.center, b.rgba))

    out.append('\n    <!-- Scripted boxes: start hidden below the floor; the scenario director moves them in -->\n')
    for name, b in c.scripted_boxes.items():
        out.append(box_model(name, b.size, c.hidden_pose(name), b.rgba))

    cl = c.centerline
    out.append('\n    <!-- Dashed centerline (visual only) -->\n    <model name="centerline">\n'
               '      <static>true</static>\n      <link name="link">\n')
    x, k = cl['x_start'], 0
    while x + cl['dash'] <= cl['x_end'] + 1e-6:
        out.append(f'        <visual name="dash_{k}"><pose>{fmt(x + cl["dash"] / 2, cl["y"], 0.002)} 0 0 0</pose>'
                   f'<geometry><box><size>{fmt(cl["dash"], cl["width"], 0.004)}</size></box></geometry>'
                   f'{material(c.colors["marking"])}</visual>\n')
        x += cl['dash'] + cl['gap']
        k += 1
    out.append('      </link>\n    </model>\n')

    r2 = c.robot2
    sx, sy, sz = r2['size']
    m = r2['mass']
    px, py, yaw = r2['park']
    out.append(f'''
    <!-- Robot 2: oncoming traffic. Driven by robot2_driver through VelocityControl (/model/robot2/cmd_vel) -->
    <model name="robot2">
      <pose>{fmt(px, py, sz / 2)} 0 0 {yaw:.4f}</pose>
      <link name="link">
        <inertial>
          <mass>{m}</mass>
          <inertia><ixx>{m * (sy**2 + sz**2) / 12:.4f}</ixx><iyy>{m * (sx**2 + sz**2) / 12:.4f}</iyy><izz>{m * (sx**2 + sy**2) / 12:.4f}</izz></inertia>
        </inertial>
        <collision name="collision"><geometry><box><size>{fmt(sx, sy, sz)}</size></box></geometry></collision>
        <visual name="visual"><geometry><box><size>{fmt(sx, sy, sz)}</size></box></geometry>{material(c.colors['robot2'])}</visual>
      </link>
      <plugin filename="gz-sim-velocity-control-system" name="gz::sim::systems::VelocityControl"/>
    </model>
''')

    td = c.cameras['topdown']
    tx, ty, tz = td['pose']
    w, h = td['size']
    # pitch +90 deg looks straight down; yaw +90 deg puts +x to image right and +y to image up
    out.append(f'''
    <!-- Top-down ground-truth camera (the audience/operator view, not robot knowledge) -->
    <model name="topdown_camera">
      <static>true</static>
      <pose>{fmt(tx, ty, tz)} 0 {math.pi / 2:.4f} {math.pi / 2:.4f}</pose>
      <link name="link">
        <sensor name="topdown" type="camera">
          <always_on>true</always_on>
          <update_rate>{td['rate']}</update_rate>
          <topic>topdown/image</topic>
          <camera>
            <horizontal_fov>{td['hfov']}</horizontal_fov>
            <image><width>{w}</width><height>{h}</height><format>R8G8B8</format></image>
            <clip><near>1.0</near><far>60</far></clip>
          </camera>
        </sensor>
      </link>
    </model>
  </world>
</sdf>
''')
    return ''.join(out)


class Grid:
    def __init__(self, c):
        m = c.map
        self.res = m['resolution']
        self.ox, self.oy = m['origin']
        self.w = int(round(m['size'][0] / self.res))
        self.h = int(round(m['size'][1] / self.res))
        xs = self.ox + (np.arange(self.w) + 0.5) * self.res
        ys = self.oy + (np.arange(self.h) + 0.5) * self.res
        self.X, self.Y = np.meshgrid(xs, ys)   # row 0 = lowest y

    def rect(self, x, y):
        return (self.X >= x[0]) & (self.X <= x[1]) & (self.Y >= y[0]) & (self.Y <= y[1])

    def files(self, name, occupied):
        img = np.where(occupied, 0, 254).astype(np.uint8)[::-1]   # pgm row 0 = top = highest y
        pgm = b'P5\n%d %d\n255\n' % (self.w, self.h) + img.tobytes()
        yml = (f'image: {name}.pgm\nmode: trinary\nresolution: {self.res}\n'
               f'origin: [{self.ox}, {self.oy}, 0.0]\nnegate: 0\n'
               f'occupied_thresh: 0.65\nfree_thresh: 0.25\n')
        return {f'maps/{name}.pgm': pgm, f'maps/{name}.yaml': yml.encode()}


def build(c):
    files = {'worlds/lpl2_corridor.sdf': world_sdf(c).encode()}
    g = Grid(c)

    static = np.zeros_like(g.X, dtype=bool)
    for b in c.static_boxes:
        static |= g.rect(b.x, b.y)
    files.update(g.files('corridor', static))

    z = c.zones
    lane1 = g.rect(z['lane1']['x'], (-z['lane1_margin'], z['lane1']['y'][1]))
    window = (g.X >= z['lane1_window']['x'][0]) & (g.X <= z['lane1_window']['x'][1])
    files.update(g.files('mask_p3_available', lane1 & ~window))
    files.update(g.files('mask_p3_unavailable', lane1))
    files.update(g.files('mask_none', np.zeros_like(lane1)))
    return files


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true', help='fail if generated files are out of date')
    args = ap.parse_args()
    c = Corridor(os.path.join(PKG, 'config', 'corridor.yaml'))
    stale = []
    for rel, data in build(c).items():
        path = os.path.join(PKG, rel)
        current = open(path, 'rb').read() if os.path.exists(path) else None
        if current == data:
            continue
        stale.append(rel)
        if not args.check:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'wb') as f:
                f.write(data)
    if args.check:
        if stale:
            print('Out of date (run tools/gen_corridor.py):', *stale, sep='\n  ')
            sys.exit(1)
        print('All generated corridor files are up to date.')
    else:
        print('Updated:', *(stale or ['nothing, all up to date']), sep='\n  ')


if __name__ == '__main__':
    main()
