#!/usr/bin/env python3
"""Generate Robot R (TurtleBot3 waffle_pi with a raised camera) from the stock TB3 files.

    python3 tools/gen_robot.py [--check]

The stock camera sits ~0.10 m above the floor, too low to see over the 0.30 m pallet.
We move only the camera frame up to robot_r.camera_height (corridor.yaml). No visible
mast is added: the gpu_lidar renders visuals, so a mast would blind it straight ahead.
A flat cyan roof plate (above the lidar plane, outside the camera view) makes Robot R
easy to spot in the top-down view. The URDF is patched the same way so TF matches
what the simulated camera sees.
Writes models/robot_r/{model.sdf,model.config} and urdf/robot_r.urdf.
"""
import argparse
import os
import sys
import xml.etree.ElementTree as ET

PKG = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, PKG)
from lpl2_sim.geometry import Corridor  # noqa: E402

TB3 = '/opt/ros/jazzy/share/turtlebot3_gazebo'
SRC_SDF = f'{TB3}/models/turtlebot3_waffle_pi/model.sdf'
SRC_URDF = f'{TB3}/urdf/turtlebot3_waffle_pi.urdf'
HEADER = ('GENERATED by lpl2_sim/tools/gen_robot.py from turtlebot3_gazebo waffle_pi '
          '(Apache-2.0, ROBOTIS). Changes: camera height, image size, cyan roof plate.')

# Roof plate: well above the lidar scan plane (~0.12 m) and behind/below the camera
BEACON = ('<visual name="lpl_roof_plate"><pose>-0.064 0 0.22 0 0 0</pose>'
          '<geometry><box><size>0.22 0.22 0.01</size></box></geometry>'
          '<material><ambient>0 0.8 0.9 1</ambient><diffuse>0 0.8 0.9 1</diffuse></material></visual>')

# URDF chain base_footprint -> base_link (z 0.010) -> camera_link (joint z) -> camera_rgb_frame (z 0.009)
URDF_BASE_Z = 0.010
URDF_RGB_Z = 0.009


def link(model, name):
    return next(lk for lk in model.findall('link') if lk.get('name') == name)


def build_sdf(cam_h, size, rate):
    tree = ET.parse(SRC_SDF)
    model = tree.getroot().find('model')
    cam = link(model, 'camera_rgb_frame')
    x = cam.find('pose').text.split()[0]
    cam.find('pose').text = f'{x} 0.0 {cam_h} 0 0 0'
    cam.find('inertial').find('pose').text = '0 0 0 0 0 0'
    sensor = cam.find('sensor')
    sensor.find('update_rate').text = str(rate)
    image = sensor.find('camera').find('image')
    image.find('width').text = str(size[0])
    image.find('height').text = str(size[1])
    link(model, 'base_link').append(ET.fromstring(BEACON))
    root = tree.getroot()
    root.insert(0, ET.Comment(f' {HEADER} '))
    return ET.tostring(root, encoding='unicode', xml_declaration=True) + '\n'


def build_urdf(cam_h):
    tree = ET.parse(SRC_URDF)
    robot = tree.getroot()
    joint = next(j for j in robot.findall('joint') if j.get('name') == 'camera_joint')
    origin = joint.find('origin')
    x, y, _ = origin.get('xyz').split()
    origin.set('xyz', f'{x} {y} {cam_h - URDF_BASE_Z - URDF_RGB_Z:.3f}')
    robot.insert(0, ET.Comment(f' {HEADER} '))
    return ET.tostring(robot, encoding='unicode', xml_declaration=True) + '\n'


MODEL_CONFIG = '''<?xml version="1.0"?>
<!-- GENERATED by lpl2_sim/tools/gen_robot.py -->
<model>
  <name>robot_r</name>
  <version>1.0</version>
  <sdf version="1.8">model.sdf</sdf>
  <description>TurtleBot3 waffle_pi with the camera raised for the LPL 2.0 corridor.</description>
</model>
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    r = Corridor(os.path.join(PKG, 'config', 'corridor.yaml')).robot_r
    files = {
        'models/robot_r/model.sdf': build_sdf(r['camera_height'], r['camera_size'], r['camera_rate']),
        'models/robot_r/model.config': MODEL_CONFIG,
        'urdf/robot_r.urdf': build_urdf(r['camera_height']),
    }
    stale = []
    for rel, text in files.items():
        path = os.path.join(PKG, rel)
        if os.path.exists(path) and open(path).read() == text:
            continue
        stale.append(rel)
        if not args.check:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'w') as f:
                f.write(text)
    if args.check:
        if stale:
            print('Out of date (run tools/gen_robot.py):', *stale, sep='\n  ')
            sys.exit(1)
        print('Robot R files are up to date.')
    else:
        print('Updated:', *(stale or ['nothing, all up to date']), sep='\n  ')


if __name__ == '__main__':
    main()
